CREATE TABLE security_event (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id       VARCHAR(100) NOT NULL,
    event_time     TIMESTAMPTZ  NOT NULL,
    received_at    TIMESTAMPTZ  NOT NULL,
    config_id      BIGINT       NOT NULL,
    policy_id      VARCHAR(100),
    client_ip      VARCHAR(45)  NOT NULL,
    hostname       VARCHAR(255) NOT NULL,
    path           TEXT         NOT NULL,
    method         VARCHAR(10)  NOT NULL,
    status_code    INTEGER      NOT NULL,
    user_agent     TEXT,
    rule_id        VARCHAR(50)  NOT NULL,
    rule_name      VARCHAR(100),
    rule_message   TEXT,
    rule_severity  VARCHAR(20)  NOT NULL,
    rule_category  VARCHAR(30)  NOT NULL,
    action         VARCHAR(10)  NOT NULL,
    geo_country    VARCHAR(2),
    geo_city       VARCHAR(100),
    request_size   BIGINT,
    response_size  BIGINT
);

CREATE INDEX idx_security_event_config_time ON security_event (config_id, event_time);
CREATE INDEX idx_security_event_time ON security_event (event_time);
